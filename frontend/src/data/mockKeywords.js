// Generate realistic 30-day sparkline trajectory around target position
const generateSparkline = (currentPos, trend = 'stable', variance = 2) => {
  const points = [];
  let pos = currentPos;
  for (let i = 29; i >= 0; i--) {
    let delta = 0;
    if (trend === 'improved') delta = (i / 30) * 4;
    else if (trend === 'declined') delta = -((i / 30) * 5);
    
    const noise = (Math.random() - 0.5) * variance;
    const value = Math.max(1, Math.min(100, Math.round(pos + delta + noise)));
    points.push(value);
  }
  points[points.length - 1] = currentPos;
  return points;
};

